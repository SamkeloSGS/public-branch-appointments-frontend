// Generates each domain's API types from the backend's OpenAPI descriptions (openapi/public.json, openapi/admin.json).
// The backend publishes two groups, public and admin, so each document is cut down to the paths a domain owns and the
// schemas those paths reach. `--check` regenerates in memory and fails if a committed file differs.
//
// springdoc marks no response property as required, although the API always writes every property (null when there
// is no value). Response schemas are therefore made fully required here, with the properties below as nullable.
import { readFile, writeFile } from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'

const NULLABLE = {
  AppointmentResponse: ['closedReason'],
  ChangeLogEntryResponse: ['changedBy'],
  CustomerResponse: ['givenName', 'familyName', 'email', 'phone'],
  CustomerSummaryResponse: ['givenName', 'familyName', 'email', 'phone'],
  DayListEntryResponse: ['customerName'],
  DeliveryResponse: ['lastError', 'lastAttemptAt', 'sentAt'],
  ExceptionResponse: ['reason'],
  MeResponse: ['displayName'],
  NotificationResponse: ['statusReason'],
  OverrideResponse: ['window', 'note'],
  PublicOfferedService: ['description'],
  PublicServiceCategoryResponse: ['description'],
  PublicServiceResponse: ['description'],
  ServiceCategoryResponse: ['description'],
  ServiceResponse: ['description'],
  StaffMemberResponse: ['email', 'invitationExpiresAt'],
}

const DOMAINS = {
  booking: [
    /^\/api\/v1\/availability/,
    /^\/api\/v1\/appointments/,
    /^\/api\/v1\/admin\/appointments/,
    /^\/api\/v1\/admin\/(schedule-impact|overbooked)$/,
    /^\/api\/v1\/admin\/notifications/,
  ],
  'branch-management': [
    /^\/api\/v1\/branch$/,
    /^\/api\/v1\/services/,
    /^\/api\/v1\/service-categories/,
    /^\/api\/v1\/admin\/branch(\/.*)?$/,
    /^\/api\/v1\/admin\/(capacity-pools|offerings|calendar-exceptions|capacity-overrides)/,
    /^\/api\/v1\/admin\/services/,
    /^\/api\/v1\/admin\/service-categories/,
  ],
  customer: [/^\/api\/v1\/customers/, /^\/api\/v1\/admin\/customers/],
  identity: [/^\/api\/v1\/me$/, /^\/api\/v1\/admin\/staff/],
}

const check = process.argv.includes('--check')

const documents = await Promise.all(
  ['public', 'admin'].map(async (group) =>
    JSON.parse(await readFile(new URL(`../openapi/${group}.json`, import.meta.url), 'utf8')),
  ),
)

function refsIn(node, found = new Set()) {
  if (Array.isArray(node)) node.forEach((item) => refsIn(item, found))
  else if (node && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      if (key === '$ref' && typeof value === 'string') found.add(value.split('/').pop())
      else refsIn(value, found)
    }
  }
  return found
}

function tighten(name, schema) {
  if (name.endsWith('Request') || !schema.properties) return schema
  const nullable = NULLABLE[name] ?? []
  const properties = Object.fromEntries(
    Object.entries(schema.properties).map(([property, definition]) => {
      if (!nullable.includes(property)) return [property, definition]
      if (definition.$ref) return [property, { oneOf: [definition, { type: 'null' }] }]
      return [property, { ...definition, type: [definition.type, 'null'] }]
    }),
  )
  return { ...schema, properties, required: Object.keys(schema.properties) }
}

// Controllers in different groups reuse method names, so operation IDs are only unique within a group.
function withGroupOperationIds(item, group) {
  return Object.fromEntries(
    Object.entries(item).map(([method, operation]) =>
      operation?.operationId ? [method, { ...operation, operationId: `${group}_${operation.operationId}` }] : [method, operation],
    ),
  )
}

function documentFor(patterns) {
  const paths = {}
  const schemas = {}
  for (const [index, document] of documents.entries()) {
    const group = index === 0 ? 'public' : 'admin'
    for (const [path, item] of Object.entries(document.paths)) {
      if (patterns.some((pattern) => pattern.test(path))) paths[path] = withGroupOperationIds(item, group)
    }
    Object.assign(schemas, document.components.schemas)
  }
  const reachable = new Set()
  const pending = [...refsIn(paths)]
  while (pending.length > 0) {
    const name = pending.pop()
    if (reachable.has(name)) continue
    reachable.add(name)
    pending.push(...refsIn(schemas[name]))
  }
  const kept = Object.fromEntries(
    [...reachable].sort().map((name) => [name, tighten(name, schemas[name])]),
  )
  return { ...documents[0], paths: Object.fromEntries(Object.entries(paths).sort()), components: { schemas: kept } }
}

let stale = false
for (const [domain, patterns] of Object.entries(DOMAINS)) {
  const header = '// Generated by scripts/generate-api.mjs from openapi/*.json. Do not edit.\n\n'
  const source = header + astToString(await openapiTS(documentFor(patterns)))
  const target = new URL(`../src/app/${domain}/model/api.generated.ts`, import.meta.url)
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => '')
    if (current.replace(/\r\n/g, '\n') !== source) {
      console.error(`src/app/${domain}/model/api.generated.ts is out of date: run npm run api:generate`)
      stale = true
    }
  } else {
    await writeFile(target, source)
    console.log(`src/app/${domain}/model/api.generated.ts`)
  }
}
if (stale) process.exit(1)
